#include <lib/syscall.h>

#include <errno.h>
#include <stdint.h>
#include <stdio.h>
#include <string.h>
#include <sys/stat.h>
#include <unistd.h>

#define RESOLV_PATH "/etc/resolv.conf"

static int update_resolv_conf(const struct net_config *config) {
  if (mkdir("/etc", 0755) < 0 && errno != EEXIST) {
    perror("netd: mkdir");
    return -1;
  }

  FILE *fp = fopen(RESOLV_PATH, "w");

  if (!fp) {
    perror("netd: fopen");
    return -1;
  }

  int failed = fprintf(fp, "# Automatically generated by Gaia netd\n") < 0;

  for (uint8_t i = 0; !failed && i < config->dns_count; i++) {

    failed = fprintf(fp,
                     "nameserver %u.%u.%u.%u\n",
                     (unsigned)config->dns[i][0],
                     (unsigned)config->dns[i][1],
                     (unsigned)config->dns[i][2],
                     (unsigned)config->dns[i][3]) < 0;
  }

  if (fclose(fp) != 0 || failed) {
    fprintf(stderr, "netd: resolver write failed\n");
    return -1;
  }

  return 0;
}

static int dns_changed(const struct net_config *a, const struct net_config *b) {
  if (a->dns_count != b->dns_count)
    return 1;

  return memcmp(a->dns, b->dns, a->dns_count * sizeof(a->dns[0])) != 0;
}

int main(void) {
  struct net_config previous = {0};
  int configured             = 0;

  for (;;) {
    struct net_config current = {0};

    if (net_config(&current) < 0) {
      sleep(1);
      continue;
    }

    if (current.dns_count > NET_CONFIG_MAX_DNS)
      current.dns_count = NET_CONFIG_MAX_DNS;

    if (!(current.flags & NET_CONFIG_DHCP_BOUND))
      current.dns_count = 0;

    if (!configured || dns_changed(&current, &previous)) {

      if (update_resolv_conf(&current) == 0) {
        previous   = current;
        configured = 1;

        printf("netd: configured %u DNS servers\n", (unsigned)current.dns_count);
      }
    }

    sleep(1);
  }

  return 0;
}
